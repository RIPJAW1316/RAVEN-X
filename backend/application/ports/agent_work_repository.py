"""Minimal persistence port for assessment-dispatch delivery records."""

from datetime import datetime, timedelta
from typing import Optional, Protocol, Tuple

from ...domain.agent_work import AgentWorkItem, LeasedAgentWork, WorkId
from ...domain.endpoint import EndpointId


class DuplicateAgentWorkError(ValueError): ...
class WorkLeaseError(ValueError): ...


class AgentWorkRepository(Protocol):
    def add(self, item: AgentWorkItem) -> None: ...
    def get(self, work_id: WorkId) -> Optional[AgentWorkItem]: ...
    def list_for_endpoint(self, endpoint_id: EndpointId) -> Tuple[AgentWorkItem, ...]: ...
    def list_for_endpoint_and_organization(self, endpoint_id: EndpointId, organization_id) -> Tuple[AgentWorkItem, ...]: ...
    def lease_next(self, endpoint_id: EndpointId, *, now: datetime, lease_duration: timedelta,
                   max_attempts: int, retry_delay: timedelta) -> Optional[LeasedAgentWork]: ...
    def acknowledge(self, work_id: WorkId, endpoint_id: EndpointId, lease_token: str, *,
                    assessment_id: str, correlation_id: str, now: datetime) -> AgentWorkItem: ...
    def mark_progress(self, endpoint_id: EndpointId, assessment_id: str, correlation_id: str, *, now: datetime) -> Optional[AgentWorkItem]: ...
    def complete(self, endpoint_id: EndpointId, assessment_id: str, correlation_id: str, *, now: datetime, failed: bool = False, error: str = None) -> Optional[AgentWorkItem]: ...
    def cancel(self, work_id: WorkId, endpoint_id: EndpointId, *, now: datetime) -> AgentWorkItem: ...
    def release_expired_leases(self, *, now: datetime, max_attempts: int, retry_delay: timedelta) -> Tuple[AgentWorkItem, ...]: ...
