"""Persistence boundary for durable control-plane assessment workflow state."""

from typing import Optional, Protocol, Tuple


class DuplicateRemoteAssessmentError(ValueError): ...
class UnknownRemoteAssessmentError(KeyError): ...
class RemoteAssessmentConflictError(ValueError): ...


class RemoteAssessmentRepository(Protocol):
    def add(self, assessment) -> None: ...
    def get(self, assessment_id: str): ...
    def exists(self, assessment_id: str) -> bool: ...
    def update(self, assessment): ...
    def list(self) -> Tuple[object, ...]: ...
    def list_non_terminal(self) -> Tuple[object, ...]: ...
    def get_for_organization(self, assessment_id, organization_id): ...
    def list_for_organization(self, organization_id) -> Tuple[object, ...]: ...
    def exists_for_organization(self, assessment_id, organization_id) -> bool: ...
    def list_for_endpoint_and_organization(self, endpoint_id, organization_id): ...
