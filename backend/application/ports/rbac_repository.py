from typing import Optional, Protocol, Tuple
from ...domain.organization import MembershipId, OrganizationId
from ...domain.rbac import Role, RoleBinding, RoleBindingId, RoleId
class DuplicateRoleError(ValueError): pass
class DuplicateRoleBindingError(ValueError): pass
class RoleRepository(Protocol):
    def add(self, role: Role) -> None: ...
    def get(self, role_id: RoleId) -> Optional[Role]: ...
    def list_for_organization(self, organization_id: OrganizationId) -> Tuple[Role, ...]: ...
    def update(self, role: Role) -> None: ...
    def exists(self, role_id: RoleId) -> bool: ...
class RoleBindingRepository(Protocol):
    def add(self, binding: RoleBinding) -> None: ...
    def get(self, binding_id: RoleBindingId) -> Optional[RoleBinding]: ...
    def list_for_membership(self, membership_id: MembershipId) -> Tuple[RoleBinding, ...]: ...
    def list_for_role(self, role_id: RoleId) -> Tuple[RoleBinding, ...]: ...
    def update(self, binding: RoleBinding) -> None: ...
    def exists(self, binding_id: RoleBindingId) -> bool: ...
