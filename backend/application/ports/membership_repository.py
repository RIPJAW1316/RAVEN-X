from typing import Optional, Protocol, Tuple
from ...domain.organization import MembershipId, OrganizationId, OrganizationMembership
from ...domain.user import UserId
class DuplicateMembershipError(ValueError): pass
class OrganizationMembershipRepository(Protocol):
    def add(self, membership: OrganizationMembership) -> None: ...
    def get(self, membership_id: MembershipId) -> Optional[OrganizationMembership]: ...
    def get_for_user_and_organization(self, user_id: UserId, organization_id: OrganizationId) -> Optional[OrganizationMembership]: ...
    def list_for_user(self, user_id: UserId) -> Tuple[OrganizationMembership, ...]: ...
    def list_for_organization(self, organization_id: OrganizationId) -> Tuple[OrganizationMembership, ...]: ...
    def update(self, membership: OrganizationMembership) -> None: ...
    def exists(self, membership_id: MembershipId) -> bool: ...
