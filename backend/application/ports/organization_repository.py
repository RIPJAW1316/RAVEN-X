from typing import Optional, Protocol, Tuple
from ...domain.organization import Organization, OrganizationId, OrganizationStatus
class DuplicateOrganizationError(ValueError): pass
class OrganizationRepository(Protocol):
    def add(self, organization: Organization) -> None: ...
    def get(self, organization_id: OrganizationId) -> Optional[Organization]: ...
    def list(self, status: Optional[OrganizationStatus] = None) -> Tuple[Organization, ...]: ...
    def update(self, organization: Organization) -> None: ...
    def exists(self, organization_id: OrganizationId) -> bool: ...
