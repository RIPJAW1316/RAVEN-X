from typing import Optional, Protocol, Tuple
from ...domain.scheduling import AssessmentSchedule, AssessmentScheduleRun

class DuplicateScheduleError(ValueError): ...
class DuplicateScheduleRunError(ValueError): ...

class AssessmentScheduleRepository(Protocol):
    def add(self, schedule: AssessmentSchedule) -> None: ...
    def get(self, schedule_id) -> Optional[AssessmentSchedule]: ...
    def update(self, schedule: AssessmentSchedule) -> None: ...
    def list_for_organization(self, organization_id) -> Tuple[AssessmentSchedule, ...]: ...
    def list_due(self, now, limit: int): ...

class AssessmentScheduleRunRepository(Protocol):
    def add_if_absent(self, run: AssessmentScheduleRun) -> bool: ...
    def get(self, schedule_id, scheduled_for) -> Optional[AssessmentScheduleRun]: ...
    def update(self, run: AssessmentScheduleRun) -> None: ...
    def list_for_schedule(self, schedule_id): ...
