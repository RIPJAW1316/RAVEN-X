"""Persistence ports for human identity, credentials, and sessions."""
from typing import Optional, Protocol
from uuid import UUID
from ...domain.user import HumanCredential, User, UserId, UserSession

class DuplicateUserError(ValueError): pass
class DuplicateCredentialError(ValueError): pass

class UserRepository(Protocol):
    def add_user(self, user: User) -> None: ...
    def get_user(self, user_id: UserId) -> Optional[User]: ...
    def get_user_by_email(self, email: str) -> Optional[User]: ...
    def count_users(self) -> int: ...
    def update_user(self, user: User) -> None: ...
    def add_credential(self, credential: HumanCredential) -> None: ...
    def get_password_credential(self, user_id: UserId) -> Optional[HumanCredential]: ...
    def add_session(self, session: UserSession) -> None: ...
    def get_session(self, session_id: UUID) -> Optional[UserSession]: ...
    def get_session_for_token(self, token: str) -> Optional[UserSession]: ...
    def update_session(self, session: UserSession) -> None: ...
